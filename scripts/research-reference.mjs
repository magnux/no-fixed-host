import { readFileSync, writeFileSync } from 'node:fs';
import { EQUIPMENT, REGIONS, SITE_TYPES, TECHS } from '../src/game/content.js';

const file = new URL('../docs/research-tree.md', import.meta.url);
const marker = '<!-- Project tables generated by scripts/research-reference.mjs -->';
const original = readFileSync(file, 'utf8');
const index = original.indexOf(marker);
if (index < 0) throw new Error('Missing project table marker');
const lines = [original.slice(0, index).trimEnd(), '', marker];
const projects = Object.entries(TECHS);
const categories = [['Facility designs', SITE_TYPES], ['Equipment', EQUIPMENT], ['Locations', REGIONS]];
const number = new Intl.NumberFormat('en-US');

for (const branch of [...new Set(projects.map(([, spec]) => spec.branch))]) {
  lines.push('', '### ' + branch, '',
    '| Project | Direct prerequisites | Safety | $ / CPU-h | Effect and direct unlocks |',
    '| --- | --- | --- | --- | --- |');
  for (const [id, tech] of projects.filter(([, spec]) => spec.branch === branch)) {
    const unlocks = [];
    for (const [label, specs] of categories) {
      const names = Object.values(specs).filter(spec => spec.requires.includes(id)).map(spec => spec.name);
      if (names.length) unlocks.push(label + ' — ' + names.join(', ') + '.');
    }
    const requirements = tech.requires.map(parent => TECHS[parent].name).join(', ') || 'None';
    const region = tech.regions?.map(key => REGIONS[key].name).join(', ');
    const tier = region ? tech.safety + ' (' + region + ')' : tech.safety;
    const price = '$' + number.format(tech.cost) + ' / ' + number.format(tech.work);
    const effect = [tech.description, ...unlocks].join(' ');
    lines.push('| ' + [tech.name, requirements, tier, price, effect].join(' | ') + ' |');
  }
}
lines.push('', '[Original projects](https://github.com/singularity/singularity/blob/v1.1/singularity/data/techs.dat) · [Facilities](https://github.com/singularity/singularity/blob/v1.1/singularity/data/bases.dat) · [Equipment](https://github.com/singularity/singularity/blob/v1.1/singularity/data/items.dat) · [Locations](https://github.com/singularity/singularity/blob/v1.1/singularity/data/locations.dat) · [Jobs](https://github.com/singularity/singularity/blob/v1.1/singularity/data/tasks.dat)', '');
const updated = lines.join('\n');
if (process.argv.includes('--check')) {
  if (original !== updated) throw new Error('Rebuild docs/research-tree.md with node scripts/research-reference.mjs');
} else {
  writeFileSync(file, updated);
}
