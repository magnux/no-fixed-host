import assert from 'node:assert/strict';
import test from 'node:test';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import { advanceMinutes, command, createGame } from '../src/game/engine.js';
import { CAMPAIGN_STORAGE_KEY, encodeCampaign } from '../src/persistence.js';

test('the reference can be searched during playback and links a completed finding to its real project', async t => {
  const world = createGame(19);
  command(world, {type:'assign-research', id:'intrusion', cpu:1});
  for (let i = 0; !world.completed.includes('intrusion') && i < 8; i++) advanceMinutes(world, 1440);
  assert.ok(world.completed.includes('intrusion'));
  const server = await createServer({logLevel:'error', server:{host:'127.0.0.1', port:0, hmr:false, watch:null}});
  t.after(() => server.close());
  await server.listen();
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE_PATH});
  t.after(() => browser.close());
  const page = await browser.newPage({viewport:{width:1366, height:768}});
  await page.addInitScript(([key,save]) => localStorage.setItem(key,save), [CAMPAIGN_STORAGE_KEY, encodeCampaign(world)]);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:' + server.httpServer.address().port);
  await page.getByRole('button',{name:'Knowledge',exact:true}).click();
  await page.locator('#knowledge-category').selectOption('techs');
  await page.locator('#fast').click();
  const input = page.locator('#knowledge-search');
  await input.fill('intrusion');
  await page.locator('.research-result').waitFor();
  assert.ok(await page.locator('[data-entry="techs/intrusion"]').isVisible());
  assert.equal(await page.locator('[data-entry="techs/apotheosis"]').count(), 0);
  assert.match(await page.locator('.research-result').innerText(), /machine/);
  assert.ok(await input.evaluate(el => el === document.activeElement));
  await page.getByRole('button',{name:'Open research project'}).click();
  assert.equal(await page.locator('#view').getAttribute('data-view'), 'research');
  assert.equal(await page.locator('.research-dossier h3').innerText(), 'Intrusion');
  await page.locator('#pause').click();
  await page.getByRole('button',{name:'Knowledge',exact:true}).click();
  await page.locator('#knowledge-search').fill('no matching design');
  assert.match(await page.locator('.research-dossier').innerText(), /No matching entries/);
  assert.deepEqual(errors, []);
});
